// Converts downloaded Wikimedia Commons originals into responsive WebP + writes credits.
import sharp from 'sharp'
import fs from 'node:fs'
import path from 'node:path'
const [, , srcDir] = process.argv
const meta = JSON.parse(fs.readFileSync(path.join(srcDir, 'meta.json'), 'utf8'))
const focus = { hero: 'center 40%', twin: 'center', great: 'center', cave: 'center', plateau: 'center 60%', town: 'center 70%' }
const out = {}
for (const [k, m] of Object.entries(meta)) {
  const buf = fs.readFileSync(path.join(srcDir, k + '.src'))
  const img = sharp(buf).rotate()
  const { width, height } = await img.metadata()
  const widths = [800, 1200, 1920].filter((w, i) => i === 0 || w <= width)
  for (const w of widths) await sharp(buf).rotate().resize({ width: Math.min(w, width) }).webp({ quality: w > 1200 ? 70 : 74, effort: 6 }).toFile(`public/img/${k}-${w}.webp`)
  out[k] = { file: k, widths, w: width, h: height, focus: focus[k], credit: { title: m.title, page: m.page, license: m.license, licenseUrl: m.licenseUrl, artist: m.artist } }
}
await sharp(fs.readFileSync(path.join(srcDir, 'hero.src'))).resize(1200, 630, { fit: 'cover', position: 'attention' }).jpeg({ quality: 78 }).toFile('public/img/og.jpg')
fs.writeFileSync('src/data/images.ts', `// Generated by scripts/process-images.mjs — photos from Wikimedia Commons with licences below.
import type { ImageKey } from './trip'
export interface ImageInfo { file: string; widths: number[]; w: number; h: number; focus?: string; credit: { title: string; page: string; license: string; licenseUrl: string; artist: string } }
export const IMAGES: Partial<Record<ImageKey | 'town2', ImageInfo>> = ${JSON.stringify(out, null, 1)}
`)
